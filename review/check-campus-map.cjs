// Optional browser acceptance checks. Install/use Playwright separately; no app dependency changes.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const base = process.env.MAP_REVIEW_URL || 'http://127.0.0.1:4173'
const output = path.resolve('outputs/campus-map')

;(async () => {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } })
  const page = await context.newPage()
  page.setDefaultTimeout(15000)
  const errors = [], external = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (!r.url().startsWith(base + '/') && !r.url().startsWith('data:')) external.push(r.url()) })
  await page.goto(base + '/review/campus-map.html')
  await page.locator('.campus-map-overlay').waitFor()
  assert.equal(await page.locator('[data-route-selected="true"]').count(), 2)
  await page.getByRole('button', { name: 'Lower estimated exposure', exact: false }).click()
  assert.equal(await page.locator('[data-route-selected="true"]').count(), 1)
  assert.equal(await page.locator('[data-segment-id="DEMO-S03"]').getAttribute('data-route-selected'), 'true')
  await page.screenshot({path:path.join(output,'resident-alternative-desktop.png'),fullPage:true})
  for (const id of ['DEMO-S01', 'DEMO-S02', 'DEMO-S03', 'DEMO-S04']) {
    await page.locator(`[data-segment-id="${id}"]`).focus()
    await page.keyboard.press('Enter')
    assert.equal(await page.getByTestId('inspector').locator(':scope > b').innerText(), id)
    assert.equal(await page.locator(`[data-segment-id="${id}"]`).getAttribute('aria-pressed'), 'true')
  }
  assert.equal(await page.locator('[data-segment-id="DEMO-S04"] .campus-shade-stroke').getAttribute('stroke'), '#707580')
  assert.match(await page.getByTestId('inspector').innerText(), /UNKNOWN/)
  await page.getByLabel('Select a segment from outside the map').selectOption('DEMO-S01')
  assert.equal(await page.locator('[data-segment-id="DEMO-S01"]').getAttribute('aria-pressed'), 'true')
  await page.locator('[data-segment-id="DEMO-S04"]').scrollIntoViewIfNeeded()
  await page.evaluate(() => new Promise(requestAnimationFrame))
  const clickPoint = await page.locator('[data-segment-id="DEMO-S04"] .campus-hit-area').evaluate(el => {
    const p = el.getPointAtLength(el.getTotalLength() * .7), m = el.getScreenCTM()
    const s = new DOMPoint(p.x,p.y).matrixTransform(m)
    return { x: s.x, y: s.y }
  })
  await page.mouse.click(clickPoint.x, clickPoint.y)
  await page.waitForFunction(() => document.querySelector('[data-testid="inspector"] > b').textContent === 'DEMO-S04', null, { timeout: 15000 })
  assert.equal(await page.getByTestId('inspector').locator(':scope > b').innerText(), 'DEMO-S04')
  await page.getByRole('button', { name: 'Add pending DEMO report' }).click()
  await page.getByRole('button', { name: 'Shortest (illustrative)', exact: false }).click()
  await page.getByLabel('Select a segment from outside the map').selectOption('DEMO-S01')
  const assertAlignment = async () => {
    const boxes = await page.evaluate(() => ['.campus-map-scene img','.campus-map-overlay'].map(s => { const r = document.querySelector(s).getBoundingClientRect(); return [r.x,r.y,r.width,r.height] }))
    assert.deepEqual(boxes[0], boxes[1])
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    return boxes[0]
  }
  const sizes = []
  for (const [width,height,label] of [[1440,1100,'desktop'],[390,844,'mobile']]) {
    console.log('Checking', label)
    await page.setViewportSize({width,height})
    await page.getByRole('button', {name:'Full map',exact:true}).click()
    sizes.push({ label, bounds: await assertAlignment() })
    for (let i=0;i<4;i++) await page.getByRole('button', {name:'Zoom in campus map',exact:true}).click()
    assert.equal(await page.locator('output').innerText(), '300%')
    assert.equal(await page.getByRole('button', {name:'Zoom in campus map',exact:true}).isDisabled(), true)
    await page.locator('.campus-map-viewport').focus()
    await page.keyboard.press('ArrowLeft')
    assert.doesNotMatch(await page.locator('.campus-map-scene').getAttribute('style'), /translate\(0px, 0px\)/)
    await assertAlignment()
    await page.keyboard.press('Home')
    assert.equal(await page.locator('output').innerText(),'100%')
    await page.getByRole('button', {name:'Zoom in campus map',exact:true}).click()
    const box = await page.locator('.campus-map-viewport').boundingBox()
    await page.mouse.move(box.x+box.width/2,box.y+box.height/2)
    await page.mouse.down()
    await page.mouse.move(box.x+box.width/2+65,box.y+box.height/2+65,{steps:8})
    await page.mouse.up()
    await assertAlignment()
    await page.getByRole('button', {name:'Recenter map',exact:true}).click()
    await page.waitForFunction(() => document.querySelector('output').textContent === '100%')
    assert.equal(await page.locator('output').innerText(),'100%')
    await page.locator('.campus-map-viewport').blur()
    await page.screenshot({ path:path.join(output,`resident-${label}.png`),fullPage:true })
    if (label === 'mobile') {
      // A touch tap exercises SVG controls at the mobile size in a touch-enabled context.
      const touch = await browser.newContext({ viewport: {width,height}, hasTouch:true, isMobile:true })
      const mobile = await touch.newPage()
      mobile.setDefaultTimeout(15000)
      await mobile.goto(base + '/review/campus-map.html')
      await mobile.locator('.campus-map-overlay').waitFor()
      await mobile.locator('[data-segment-id="DEMO-S04"]').scrollIntoViewIfNeeded()
      await mobile.evaluate(() => new Promise(requestAnimationFrame))
      const p = await mobile.locator('[data-segment-id="DEMO-S04"] .campus-hit-area').evaluate(el => {
        const p = el.getPointAtLength(el.getTotalLength()*.7), s = new DOMPoint(p.x,p.y).matrixTransform(el.getScreenCTM()); return {x:s.x,y:s.y}
      })
      await mobile.touchscreen.tap(p.x,p.y)
      await mobile.waitForFunction(() => document.querySelector('[data-testid="inspector"] > b').textContent === 'DEMO-S04', null, { timeout: 15000 })
      assert.equal(await mobile.getByTestId('inspector').locator(':scope > b').innerText(),'DEMO-S04')
      await touch.close()
    }
  }
  await page.setViewportSize({width:1440,height:1100})
  console.log('Checking developer state')
  await page.getByRole('button', {name:'Developer review',exact:true}).click()
  assert.equal(await page.locator('.campus-candidate').count(),1)
  assert.equal(await page.locator('.campus-candidate').getAttribute('data-intervention-id'),'INT-03')
  const colours = await page.locator('.campus-shade-stroke').evaluateAll(els => els.map(e=>e.getAttribute('stroke')))
  await page.getByRole('button',{name:'Toggle SIMULATED sites',exact:true}).click()
  assert.equal(await page.locator('.campus-candidate').getAttribute('data-scenario'),'true')
  assert.deepEqual(await page.locator('.campus-shade-stroke').evaluateAll(els=>els.map(e=>e.getAttribute('stroke'))),colours)
  assert.equal(await page.locator('.campus-report').count(),1)
  assert.match(await page.locator('.campus-report title').textContent(),/DEMO-S04/)
  await page.getByLabel('Review budget (RM)').fill('10000')
  assert.equal(await page.locator('.campus-candidate').getAttribute('data-intervention-id'),'INT-02')
  await page.locator('.campus-candidate').focus()
  await page.keyboard.press('Space')
  assert.equal(await page.getByTestId('inspector').locator(':scope > b').innerText(),'DEMO-S02')
  await page.screenshot({path:path.join(output,'developer-desktop.png'),fullPage:true})
  await page.getByLabel('Review budget (RM)').fill('0')
  assert.equal(await page.locator('.campus-candidate').count(),0)
  assert.equal(await page.getByText('No selected intervention sites.',{exact:true}).isVisible(),true)
  const failure = await context.newPage()
  await failure.route('**/maps/utmkul-campus-map.png*', r => r.abort())
  await failure.goto(base + '/review/campus-map.html')
  await failure.getByRole('alert').waitFor()
  assert.equal(await failure.locator('.campus-map-overlay').count(),0)
  await failure.screenshot({path:path.join(output,'image-load-error.png'),fullPage:true})
  await failure.unroute('**/maps/utmkul-campus-map.png*')
  await failure.getByRole('button',{name:'Retry campus image',exact:true}).click()
  await failure.locator('.campus-map-overlay').waitFor()
  assert.deepEqual(errors,[])
  assert.deepEqual(external,[])
  const results = { status:'passed', scope:'Standalone component production review build. Integrated application checks are recorded separately in integrated/browser-results.json.', checks:['route segment ID/highlight agreement','keyboard, mouse and mobile touch segment selection','external selection updates SVG state','grey unknown and DEMO evidence','image/SVG alignment at desktop, mobile, zoom and pan','zoom limits and recenter','candidate changes with RM budget','scenario does not change baseline shade','report linked to correct segment','empty portfolio','image load failure hides overlays and retry recovers','no external requests in review page','no review page exceptions'], imageBounds:sizes, externalRequests:external, browserErrors:errors }
  await fs.writeFile(path.join(output,'browser-results.json'),JSON.stringify(results,null,2)+'\n')
  console.log(JSON.stringify(results,null,2))
  await browser.close()
})().catch(e=>{console.error(e);process.exit(1)})
