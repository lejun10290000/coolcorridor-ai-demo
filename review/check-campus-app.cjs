const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const base = process.env.CAMPUS_APP_URL || 'http://127.0.0.1:4174'
const output = path.resolve('outputs/campus-map/integrated')
;(async () => {
  await fs.mkdir(output,{recursive:true})
  const browser = await chromium.launch({headless:true,...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})})
  const context = await browser.newContext({viewport:{width:1440,height:1100},reducedMotion:'reduce'})
  const page = await context.newPage()
  page.setDefaultTimeout(15000)
  const errors=[],external=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(!r.url().startsWith(base+'/')&&!r.url().startsWith('data:'))external.push(r.url())})
  await page.goto(base+'/')
  await page.getByLabel('Visual quality').selectOption('fallback')
  assert.equal(await page.getByRole('button',{name:'Enter Resident Mode',exact:true}).isVisible(),true)
  assert.equal(await page.getByRole('button',{name:'Enter Developer Mode',exact:true}).isVisible(),true)
  await page.getByRole('button',{name:'Enter Resident Mode',exact:true}).click()
  await page.locator('.campus-map-overlay').waitFor()
  assert.equal(await page.locator('.campus-map-scene img').getAttribute('src'),'/maps/utmkul-campus-map.png')
  assert.equal(await page.locator('.leaflet-container').count(),0)
  assert.equal(await page.locator('[data-route-selected="true"]').count(),2)
  await page.locator('.route-card').filter({hasText:'Lower estimated exposure'}).click()
  assert.equal(await page.locator('[data-route-selected="true"]').count(),1)
  assert.equal(await page.locator('[data-segment-id="DEMO-S03"]').getAttribute('data-route-selected'),'true')
  await page.getByRole('button',{name:'Compare demo routes',exact:true}).click()
  assert.match(await page.locator('.endpoint .success').innerText(),/no live route calculation/)
  for(const id of ['DEMO-S01','DEMO-S02','DEMO-S03','DEMO-S04']){
    await page.locator(`[data-segment-id="${id}"]`).focus()
    await page.keyboard.press('Enter')
    await page.waitForFunction(id=>document.querySelector('.inspector code').textContent===id,id)
    assert.equal(await page.locator('.inspector code').innerText(),id)
  }
  assert.match(await page.locator('.inspector').innerText(),/UNKNOWN/)
  assert.match(await page.locator('.inspector').innerText(),/Unknown \/ no observed timestamp/)
  assert.equal(await page.locator('[data-segment-id="DEMO-S04"] .campus-shade-stroke').getAttribute('stroke'),'#707580')
  // Verify a real pointer release updates the operational inspector.
  await page.locator('[data-segment-id="DEMO-S01"]').scrollIntoViewIfNeeded()
  const point=await page.locator('[data-segment-id="DEMO-S01"] .campus-hit-area').evaluate(el=>{const p=el.getPointAtLength(el.getTotalLength()*.4),s=new DOMPoint(p.x,p.y).matrixTransform(el.getScreenCTM());return{x:s.x,y:s.y}})
  await page.mouse.click(point.x,point.y)
  await page.waitForFunction(()=>document.querySelector('.inspector code').textContent==='DEMO-S01')
  await page.getByRole('button',{name:'Report this walkway',exact:true}).click()
  await page.getByLabel('Optional note').fill('Browser verification: pending DEMO report')
  await page.getByRole('button',{name:'Submit demo report',exact:true}).click()
  assert.equal(await page.locator('.campus-report').count(),1)
  assert.match(await page.locator('.endpoint .success').innerText(),/pending review/)
  const checkAlignment=async()=>{
    const boxes=await page.evaluate(()=>['.campus-map-scene img','.campus-map-overlay'].map(s=>{const r=document.querySelector(s).getBoundingClientRect();return[r.x,r.y,r.width,r.height]}))
    assert.deepEqual(boxes[0],boxes[1]);assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  }
  for(const [width,height,label] of [[1440,1100,'desktop'],[390,844,'mobile']]){
    await page.setViewportSize({width,height})
    await page.getByRole('button',{name:'Full map',exact:true}).click()
    await checkAlignment()
    await page.screenshot({path:path.join(output,`resident-${label}.png`),fullPage:true})
    await page.getByRole('button',{name:'Zoom in campus map',exact:true}).click()
    await page.locator('.campus-map-viewport').focus();await page.keyboard.press('ArrowLeft')
    await checkAlignment()
    await page.getByRole('button',{name:'Recenter map',exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('output').textContent==='100%')
  }
  await page.setViewportSize({width:1440,height:1100})
  await page.getByRole('button',{name:'← Home',exact:true}).click()
  await page.getByLabel('Visual quality').selectOption('fallback')
  await page.getByRole('button',{name:'Enter Developer Mode',exact:true}).click()
  await page.locator('.campus-map-overlay').waitFor()
  assert.equal(await page.locator('.campus-map-scene img').getAttribute('src'),'/maps/utmkul-campus-map.png')
  assert.equal(await page.locator('.campus-report').count(),1)
  assert.match(await page.locator('.report').innerText(),/DEMO-S01 · submitted/)
  assert.equal(await page.locator('.campus-candidate').getAttribute('data-intervention-id'),'INT-03')
  await page.locator('.priority').filter({hasText:'DEMO-S02'}).click()
  assert.equal(await page.locator('[data-segment-id="DEMO-S02"]').getAttribute('aria-pressed'),'true')
  const colours=await page.locator('.campus-shade-stroke').evaluateAll(es=>es.map(e=>e.getAttribute('stroke')))
  await page.getByLabel('Available budget (RM)').fill('10000')
  assert.equal(await page.locator('.campus-candidate').getAttribute('data-intervention-id'),'INT-02')
  await page.getByRole('button',{name:'Optimise plan',exact:true}).click()
  assert.equal(await page.locator('.campus-candidate').getAttribute('data-scenario'),'true')
  assert.deepEqual(await page.locator('.campus-shade-stroke').evaluateAll(es=>es.map(e=>e.getAttribute('stroke'))),colours)
  for(const [width,height,label] of [[1440,1100,'desktop'],[390,844,'mobile']]){
    await page.setViewportSize({width,height});await page.getByRole('button',{name:'Full map',exact:true}).click();await checkAlignment()
    await page.screenshot({path:path.join(output,`developer-${label}.png`),fullPage:true})
  }
  await page.setViewportSize({width:1440,height:1100})
  await page.getByRole('button',{name:'Return to baseline',exact:true}).click()
  assert.equal(await page.locator('.campus-candidate').getAttribute('data-scenario'),'false')
  await page.getByRole('button',{name:'Under review',exact:true}).click()
  assert.match(await page.locator('.report').innerText(),/under_review/)
  await page.getByRole('button',{name:'Verify',exact:true}).click()
  assert.match(await page.locator('.report').innerText(),/verified/)
  // Existing lifecycle is exercised without changing its implementation.
  const lifecycle=page.locator('.lifecycle').filter({hasText:'INT-01'})
  for(let i=0;i<5;i++)await lifecycle.getByRole('button').click()
  assert.match(await lifecycle.innerText(),/Published demo data/)
  await page.getByLabel('Available budget (RM)').fill('0')
  assert.equal(await page.locator('.campus-candidate').count(),0)
  assert.match(await page.locator('.result').innerText(),/No selected interventions/)
  // Asset failure has no map tiles or silent online fallback.
  const failure=await context.newPage()
  failure.setDefaultTimeout(15000)
  await failure.route('**/maps/utmkul-campus-map.png*',r=>r.abort())
  await failure.goto(base+'/')
  await failure.getByLabel('Visual quality').selectOption('fallback')
  await failure.getByRole('button',{name:'Enter Resident Mode',exact:true}).click()
  await failure.getByRole('alert').waitFor()
  assert.equal(await failure.locator('.campus-map-overlay').count(),0)
  await failure.unroute('**/maps/utmkul-campus-map.png*')
  await failure.getByRole('button',{name:'Retry campus image',exact:true}).click()
  await failure.locator('.campus-map-overlay').waitFor()
  assert.deepEqual(errors,[]);assert.deepEqual(external,[])
  const result={status:'passed',scope:'Integrated production application at /',checks:['Home role portals and fallback','Resident route card/highlight IDs','DEMO comparison labels','all four segments select inspector','pointer segment selection','unknown shade/timestamp','resident pending report shown in Developer','1440px/390px Resident and Developer image/SVG alignment; no overflow','zoom pan recenter','Developer priority selects matching segment','budget marker recomputation and zero-budget empty plan','scenario toggle preserves baseline shade','report review and lifecycle remain usable','image load failure and recovery','no external requests or browser exceptions in observed run'],externalRequests:external,browserErrors:errors}
  await fs.writeFile(path.join(output,'browser-results.json'),JSON.stringify(result,null,2)+'\n')
  console.log(JSON.stringify(result,null,2))
  await browser.close()
})().catch(e=>{console.error(e);process.exit(1)})
